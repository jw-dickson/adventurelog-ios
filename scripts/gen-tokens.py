"""Generate Packages/ALDesign/Sources/ALDesign/Tokens.swift from Design/tokens.json.

Design/tokens.json is exported from the "AdventureLog iOS" design system in Claude Design.
Never edit Tokens.swift by hand: change the design system, export tokens.json, and rerun.

    python3 scripts/gen-tokens.py           # write Tokens.swift
    python3 scripts/gen-tokens.py --check   # exit 1 if Tokens.swift is stale (CI)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Design" / "tokens.json"
TARGET = ROOT / "Packages" / "ALDesign" / "Sources" / "ALDesign" / "Tokens.swift"

TEXT_STYLE_BY_SIZE = {
    34: "largeTitle", 28: "title", 24: "title2", 22: "title2", 20: "title3", 17: "body",
    16: "callout", 15: "subheadline", 13: "footnote", 12: "caption", 11: "caption2",
}
WEIGHTS = {300: "light", 400: "regular", 500: "medium", 600: "semibold", 700: "bold", 800: "heavy"}
DESIGNS = {"mono": "monospaced", "display": "default", "sans": "default"}
SWIFT_KEYWORDS = {"default", "case", "class", "struct", "let", "var", "in", "is", "as", "func"}


def ident(name: str, strip: str = "") -> str:
    """Convert a token name to camel case, optionally removing a prefix.

    Prefix leading digits with an underscore and escape the recognized Swift keywords.
    """
    if strip and name.startswith(strip):
        name = name[len(strip):]
    parts = re.split(r"[-_.\s]+", name)
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if out[:1].isdigit():
        out = "_" + out
    return f"`{out}`" if out in SWIFT_KEYWORDS else out


def rgba(value: str):
    """Parse 3-, 4-, 6-, or 8-digit hex into RGB channels (0–255) and alpha (0–1).

    Alpha defaults to 1 and is rounded to three decimals. Raise ValueError for invalid hex.
    """
    v = value.strip().lstrip("#")
    if len(v) in (3, 4):
        v = "".join(c * 2 for c in v)
    if len(v) == 6:
        v += "ff"
    if len(v) != 8 or not re.fullmatch(r"[0-9a-fA-F]{8}", v):
        raise ValueError(f"unsupported colour {value!r}: tokens.json colours must be hex for the Swift generator")
    r, g, b, a = (int(v[i:i + 2], 16) for i in (0, 2, 4, 6))
    return r, g, b, round(a / 255, 3)


def resolve(tokens: dict, name: str, theme: str, depth: int = 0) -> str:
    """Resolve a token and its aliases for a theme, falling back to the light value.

    Raise KeyError for missing tokens and ValueError when alias depth exceeds 16;
    malformed non-string values propagate TypeError from pattern matching.
    """
    if depth > 16:
        raise ValueError(f"alias chain too deep at {name}")
    value = tokens[name]
    raw = value.get(theme, value.get("light")) if isinstance(value, dict) else value
    m = re.fullmatch(r"\{(.+)\}", raw)
    return resolve(tokens, m.group(1), theme, depth + 1) if m else raw


def comment(text: str) -> str:
    """Collapse whitespace into a single line for a generated Swift documentation comment."""
    return " ".join((text or "").split())


def generate() -> str:
    """Read SOURCE and return generated Swift without writing TARGET.

    Propagate file, JSON, and token-shape errors; raise ValueError for unsupported
    themes, colors, alias depth, or Dynamic Type sizes.
    """
    data = json.loads(SOURCE.read_text())
    color_tokens = data["color"]["tokens"]
    by_name = {t["name"]: t["value"] for t in color_tokens}
    themes = [t["id"] for t in data["color"]["themes"]]
    if themes[:2] != ["light", "dark"]:
        raise ValueError("expected themes light, dark")

    out = [
        "// AdventureLog for iOS — Copyright (C) 2026 the AdventureLog iOS contributors. GPL-3.0-or-later.",
        "//",
        "// GENERATED by scripts/gen-tokens.py from Design/tokens.json. Do not edit.",
        f"// Source: {comment(data.get('meta', {}).get('source', 'AdventureLog iOS design system'))}",
        "",
        "import SwiftUI",
        "",
        "/// Colours from the AdventureLog iOS design system. Each adapts to light and dark appearance.",
        "public enum ALColor {",
    ]
    for t in color_tokens:
        light = rgba(resolve(by_name, t["name"], "light"))
        dark = rgba(resolve(by_name, t["name"], "dark"))
        out.append(f"    /// {comment(t.get('usage', ''))}")
        out.append(
            f"    public static let {ident(t['name'])} = Color(light: .init({light[0]}, {light[1]}, {light[2]}, {light[3]}), "
            f"dark: .init({dark[0]}, {dark[1]}, {dark[2]}, {dark[3]}))"
        )
    out += ["}", ""]

    out += ["/// Spacing steps in points.", "public enum ALSpace {"]
    for t in data.get("spacing", {}).get("tokens", []):
        out.append(f"    /// {comment(t.get('usage', ''))}")
        out.append(f"    public static let {ident(t['name'])}: CGFloat = {float(str(t['value']).rstrip('px'))}")
    out += ["}", ""]

    out += ["/// Corner radii in points (AdventureLog's own --rounded-* values).", "public enum ALRadius {"]
    for t in data.get("radius", {}).get("tokens", []):
        out.append(f"    /// {comment(t.get('usage', ''))}")
        out.append(f"    public static let {ident(t['name'], 'radius-')}: CGFloat = {float(str(t['value']).rstrip('px'))}")
    out += ["}", ""]

    out += [
        "/// Type styles mapped onto Dynamic Type text styles, so every one scales with the user's setting.",
        "public enum ALFont {",
    ]
    for group in data["type"]["groups"]:
        for s in group["styles"]:
            size = round(float(str(s["fontSize"]).rstrip("px")))
            style = TEXT_STYLE_BY_SIZE.get(size)
            if not style:
                raise ValueError(f"no Dynamic Type style for {s['name']} at {size}pt")
            weight = WEIGHTS.get(int(str(s.get("fontWeight", 400)).split()[0]), "regular")
            design = DESIGNS.get(s.get("family", group["family"]), "default")
            out.append(f"    /// {size}pt. {comment(s.get('usage', ''))}")
            out.append(f"    public static let {ident(s['name'])} = Font.system(.{style}, design: .{design}, weight: .{weight})")
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    """Write generated tokens, or return 1 for stale output when --check is present.

    Return 0 on success; generation and file-system errors propagate.
    """
    text = generate()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is stale. Run: python3 scripts/gen-tokens.py", file=sys.stderr)
            return 1
        print("Tokens.swift is up to date.")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text)
    print(f"Wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
